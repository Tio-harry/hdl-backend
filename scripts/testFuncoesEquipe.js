const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
if (require.main === module) {
  // Standalone invocation uses the same isolated DB harness, never an operational DB.
  const result = require('node:child_process').spawnSync(process.execPath, [path.join(__dirname, 'testNoiteNatal.js')], { stdio: 'inherit' });
  process.exitCode = result.status ?? 1;
}
module.exports = async function testFuncoesEquipe({ db, request, base, hash }) {
  const sql = fs.readFileSync(path.join(__dirname, '../db/migrations/002_funcoes_equipe.sql'), 'utf8');
  await db.query("INSERT INTO eventos(id,contratante_nome,data_evento) VALUES('funcao-history-event','Historico teste','01/01/2032')");
  await db.query("INSERT INTO escala_eventos(id,evento_id,colaborador_id,colaborador_nome,funcao) VALUES('funcao-history-scale','funcao-history-event','noel-test','Noel teste','Apoio histórico')");
  const before = (await db.query('SELECT * FROM escala_eventos ORDER BY id')).rows;
  const eventsBefore = (await db.query('SELECT * FROM eventos ORDER BY id')).rows;
  const contractsBefore = (await db.query('SELECT * FROM contracts ORDER BY id')).rows;
  await db.query(sql); await db.query(sql);
  assert.deepEqual((await db.query('SELECT * FROM escala_eventos ORDER BY id')).rows, before);
  let list = await request('/funcoes-equipe');
  for (const nome of ['Recreador','Personagem','Promotor','Staff','Papai Noel','Assistente/Duende','Motorista','Apoio histórico']) assert.ok(list.some((f) => f.nome === nome), nome);
  assert.equal((await fetch(`${base}/funcoes-equipe`)).status, 401);
  await db.query("INSERT INTO usuarios(id,nome,email,senha_hash,perfil) VALUES('role-operator','Operador','role-test@example.invalid',$1,'operador')", [hash]);
  const login = await fetch(`${base}/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'role-test@example.invalid', senha: 'Teste-Natal-Local-2026' }) });
  const cookie = login.headers.get('set-cookie').split(';')[0];
  assert.equal((await fetch(`${base}/funcoes-equipe`, { headers: { Cookie: cookie } })).status, 200);
  assert.equal((await fetch(`${base}/funcoes-equipe/admin`, { headers: { Cookie: cookie } })).status, 403);
  assert.equal((await fetch(`${base}/funcoes-equipe`, { method: 'POST', headers: { Cookie: cookie, 'Content-Type': 'application/json' }, body: JSON.stringify({ nome: 'Nao criar' }) })).status, 403);
  list = await request('/funcoes-equipe', { nome: '  Apoio   externo ' }, 'POST');
  const created = list.find((f) => f.nome === 'Apoio externo'); assert.ok(created);
  await request('/funcoes-equipe', { nome: 'APOIO EXTERNO' }, 'POST', 409);
  await request('/funcoes-equipe', { nome: '' }, 'POST', 400);
  await request('/funcoes-equipe/ordem', { ids: [created.id, created.id] }, 'PUT', 409);
  const ids = list.map((f) => f.id).reverse();
  await request('/funcoes-equipe/ordem', { ids }, 'PUT');
  assert.deepEqual((await request('/funcoes-equipe/admin')).map((f) => f.id), ids);
  const scale = await request('/eventos/funcao-history-event/escalas', { colaborador_id: 'noel-test', funcao: 'Apoio externo' }, 'POST', 201);
  const financeSql = "SELECT valor_total,sinal,resta,pagamento_colaborador,status_financeiro FROM eventos WHERE id='funcao-history-event'";
  const financeBefore = (await db.query(financeSql)).rows;
  await request(`/funcoes-equipe/${created.id}`, { nome: 'Apoio externo novo' }, 'PUT');
  assert.equal((await db.query('SELECT funcao FROM escala_eventos WHERE id=$1', [scale.id])).rows[0].funcao, 'Apoio externo');
  await request(`/escalas-evento/${scale.id}`, { funcao: 'Apoio externo' });
  await request(`/funcoes-equipe/${created.id}`, { ativo: false }, 'PUT');
  assert.ok(!(await request('/funcoes-equipe')).some((f) => f.id === created.id));
  await request('/eventos/funcao-history-event/escalas', { colaborador_id: 'noel-test', funcao: 'Apoio externo novo' }, 'POST', 400);
  await request(`/escalas-evento/${scale.id}`, { funcao: 'Apoio externo novo' }, 'PUT', 400);
  await request(`/escalas-evento/${scale.id}`, { funcao: 'Inventada' }, 'PUT', 400);
  await request(`/funcoes-equipe/${created.id}`, { ativo: true }, 'PUT');
  assert.ok((await request('/funcoes-equipe')).some((f) => f.id === created.id));
  assert.deepEqual((await db.query("SELECT * FROM escala_eventos WHERE id <> $1 ORDER BY id", [scale.id])).rows, before);
  assert.deepEqual((await db.query("SELECT * FROM eventos WHERE id <> 'funcao-history-event' ORDER BY id")).rows, eventsBefore.filter((e) => e.id !== 'funcao-history-event'));
  assert.deepEqual((await db.query('SELECT * FROM contracts ORDER BY id')).rows, contractsBefore);
  assert.deepEqual((await db.query(financeSql)).rows, financeBefore);
  await assert.rejects(db.query("INSERT INTO funcoes_equipe(id,nome,ordem) VALUES('duplicate',' MOTORISTA ',1)"), (e) => e.code === '23505');
  await assert.rejects(db.query("INSERT INTO funcoes_equipe(id,nome,ordem) VALUES('invalid','Invalida',-1)"), (e) => e.code === '23514');
  const indexes = (await db.query("SELECT indexname FROM pg_indexes WHERE tablename='funcoes_equipe'")).rows;
  assert.ok(indexes.some((i) => i.indexname === 'funcoes_equipe_ativo_ordem_idx'));
  console.log('PASS funcoes: migration repetivel/seeds/historico; sessao/permissoes; CRUD; duplicidade; ordem; inativa/renomeada preserva escala; escolhas invalidas bloqueadas; demais eventos/contratos intactos');
};
